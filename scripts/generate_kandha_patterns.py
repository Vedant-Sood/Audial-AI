"""Generate firmware/kandha/patterns.h from browser/sanket/kandha-patterns.json.

The JSON table is the single source of truth for the Kandha tap language. This script writes the
C header the firmware compiles in, so the stole plays exactly the steps the app, the virtual
stole and the tests use.

    python scripts/generate_kandha_patterns.py            # write the header
    python scripts/generate_kandha_patterns.py --check    # exit 1 if the header is out of date
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "browser" / "sanket" / "kandha-patterns.json"
TARGET = ROOT / "firmware" / "kandha" / "patterns.h"


def uuid_bytes(text):
    """A 128-bit UUID as the little-endian byte list the ESP32 BLE stack expects."""
    raw = bytes.fromhex(text.replace("-", ""))
    return ", ".join(f"0x{b:02x}" for b in reversed(raw))


def render(data):
    digest = hashlib.sha256(json.dumps(data, sort_keys=True, separators=(",", ":")).encode()).hexdigest()[:16]
    p = data["protocol"]
    out = ["// Generated by scripts/generate_kandha_patterns.py from browser/sanket/kandha-patterns.json.",
           "// Do not edit: change the JSON and run the generator. Table digest: " + digest,
           "#pragma once", "#include <stdint.h>", "",
           f"#define KANDHA_TABLE_DIGEST \"{digest}\"",
           f"#define KANDHA_PROTOCOL_VERSION {int(data['version'])}",
           f"#define KANDHA_NAME_PREFIX \"{p['name_prefix']}\"",
           f"#define KANDHA_SERVICE_UUID \"{p['service_uuid']}\"",
           f"#define KANDHA_CHAR_HAPTIC_UUID \"{p['characteristics']['haptic']}\"",
           f"#define KANDHA_CHAR_PATTERNS_UUID \"{p['characteristics']['patterns']}\"",
           f"#define KANDHA_CHAR_INPUT_UUID \"{p['characteristics']['input']}\"",
           f"#define KANDHA_CHAR_STATUS_UUID \"{p['characteristics']['status']}\"",
           f"#define KANDHA_CHAR_CONFIG_UUID \"{p['characteristics']['config']}\"",
           f"#define KANDHA_MAX_PATTERN_STEPS {int(p['max_pattern_steps'])}",
           f"#define KANDHA_BUILTIN_PATTERN_MAX {int(p['builtin_pattern_ids'][1])}",
           f"#define KANDHA_LOW_BATTERY_PERCENT {int(data['scheduler']['low_battery_percent'])}", ""]
    for zone, info in data["zones"].items():
        out.append(f"#define KANDHA_ZONE_{zone} {int(info['bit'])}  // {info['name']}")
    out.append("")
    for pad, value in data["pads"].items():
        out.append(f"#define KANDHA_PAD_{pad} {int(value)}")
    for gesture, value in data["gestures"].items():
        out.append(f"#define KANDHA_GESTURE_{gesture.upper()} {int(value)}")
    out += ["", "struct KandhaStep { uint16_t on_ms; uint16_t off_ms; uint8_t level; };",
            "struct KandhaPattern { uint8_t id; const char* key; uint8_t zones; uint8_t intensity; uint8_t repeat; uint8_t count; const KandhaStep* steps; };", ""]
    for item in data["patterns"]:
        steps = ", ".join(f"{{{int(s['on_ms'])}, {int(s['off_ms'])}, {int(s['level'])}}}" for s in item["steps"]) or "{0, 0, 0}"
        out.append(f"static const KandhaStep kandha_steps_{item['key']}[] = {{{steps}}};")
    out.append("")
    out.append("static const KandhaPattern KANDHA_PATTERNS[] = {")
    for item in data["patterns"]:
        zones = item["zones"]
        mask = 0 if zones in ("seat", "any", "none") else sum(int(data["zones"][z]["bit"]) for z in zones)
        out.append(f"  {{{int(item['id'])}, \"{item['key']}\", {mask}, {int(item['intensity'])}, {int(item['repeat'])}, {len(item['steps'])}, kandha_steps_{item['key']}}},  // {item['name']}")
    out += ["};", f"#define KANDHA_PATTERN_COUNT {len(data['patterns'])}", "",
            "// The service UUID as little-endian bytes, for advertising data.",
            f"static const uint8_t KANDHA_SERVICE_UUID_LE[16] = {{{uuid_bytes(p['service_uuid'])}}};", ""]
    return "\n".join(out)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="Verify the header matches the JSON without writing")
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument("--target", type=Path, default=TARGET)
    args = parser.parse_args(argv)
    text = render(json.loads(args.source.read_text(encoding="utf-8")))
    if args.check:
        current = args.target.read_text(encoding="utf-8") if args.target.exists() else ""
        if current != text:
            print(f"{args.target} is out of date; run python scripts/generate_kandha_patterns.py", file=sys.stderr)
            return 1
        print("firmware pattern header is up to date")
        return 0
    args.target.parent.mkdir(parents=True, exist_ok=True)
    args.target.write_text(text, encoding="utf-8")
    print(f"wrote {args.target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
